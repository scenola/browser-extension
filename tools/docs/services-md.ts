// `pnpm docs:services` writes docs/services.md from the service registry: every
// built-in site, its hosts, whether a module reads it or the generic readers do, what the module
// asks the page for, and when it was last verified. `pnpm docs:services --check` regenerates it
// in memory and fails when the committed file differs — the registry is the one edit point, the
// page follows it. Nothing here depends on the day: whether a store build ships a module today
// is a rule (90 days), stated, not a fact the page would have to be regenerated for.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

import { format, resolveConfig } from 'prettier';

import type { BuiltInSite } from '../../packages/services/src/registry.ts';
import type { CollectSpec, ServiceDefinition } from '../../packages/services/src/sdk.ts';
import { loadServices } from './load-services.ts';

const OUTPUT = fileURLToPath(new URL('../../docs/services.md', import.meta.url));

/** A code span that holds `text` whatever backticks it contains (CommonMark §6.1). */
function code(text: string): string {
  let longest = 0;
  let run = 0;
  for (const char of text) {
    run = char === '`' ? run + 1 : 0;
    longest = Math.max(longest, run);
  }
  const fence = '`'.repeat(longest + 1);
  const pad = text.startsWith('`') || text.endsWith('`') ? ' ' : '';
  return `${fence}${pad}${text}${pad}${fence}`;
}

/** Text in a table cell: markup characters escaped, the cell separator too. */
const cell = (text: string): string => text.replace(/[\\`*_[\]<>|]/gu, '\\$&');

/**
 * What a module asks the page for, in words: the kinds of input (and the query parameters by
 * name, since a URL is personal), not their spelling — that is the module's README, and a page
 * that moved with every selector would be stale after every fix.
 */
function reads(collect: CollectSpec): string[] {
  const out = ['the player route'];
  if (Object.keys(collect.selectors ?? {}).length > 0) out.push('page text');
  if (Object.keys(collect.pageState ?? {}).length > 0) out.push("the player's own state");
  if (collect.jsonLd === true) out.push('JSON-LD');
  if (collect.mediaSession === true) out.push('Media Session');
  if (collect.openGraph === true) out.push('Open Graph');
  const query = collect.queryParams ?? [];
  if (query.length > 0) out.push(`query parameters ${query.map(code).join(', ')}`);
  if (collect.signals?.endOfContent !== undefined) out.push('an end-of-content signal');
  if (collect.signals?.adPlaying !== undefined) out.push('an ad signal');
  if (collect.shadowRootPlayer === true) out.push('a player inside shadow roots');
  return out;
}

function verifiedText(module: ServiceDefinition): string {
  return module.verified === null
    ? 'not yet'
    : `${module.verified.on}, by ${cell(module.verified.by)}`;
}

/** docs/services.md for `sites`, formatted as the repository's Prettier would. */
export async function servicesMarkdown(sites: readonly BuiltInSite[]): Promise<string> {
  const lines = [
    '<!-- Generated by `pnpm docs:services` from packages/services/src/registry.ts. Do not edit:',
    '     change the registry or a module and run it again; CI runs it with --check. -->',
    '',
    '# Services',
    '',
    'The sites the Scenola extension tracks from its first release, from the service registry',
    "(`packages/services/src/registry.ts`). Every host below is in the first release's host",
    'permissions, so a service never arrives through a new permission prompt. Any',
    'other film or TV site can be allowed from Settings or the popup, and is read by the generic',
    'readers.',
    '',
    '- **Module**: a service module reads the player. A store build ships it only while',
    '  its verification is at most 90 days old, and leaves the site to the generic readers',
    '  otherwise.',
    '- **Generic readers**: the readers every site gets — JSON-LD, Media Session, Open Graph, the',
    "  document title and the page's address. A viewing starts only when the page itself says it",
    '  is a film or an episode, or a series whose address names the episode.',
    '',
    '| Id | Service | Hosts | Read by | Verified |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const site of sites) {
    const module = site.module;
    const cells = [
      code(site.id),
      cell(site.name),
      site.hosts.map(code).join(', '),
      module === null ? 'generic readers' : `module ${module.version}`,
      module === null ? '—' : verifiedText(module),
    ];
    lines.push(`| ${cells.join(' | ')} |`);
  }

  const modules = sites.flatMap((site) => (site.module === null ? [] : [site.module]));
  if (modules.length > 0) {
    lines.push('', '## What each module asks the page for', '');
    for (const module of modules) {
      lines.push(
        `- **${cell(module.name)}** (${code(module.id)}): ${reads(module.collect).join(', ')}.` +
          ` [README](../packages/services/src/services/${module.id}/README.md)`,
      );
    }
  }
  lines.push(
    '',
    'Adding or fixing a service is one folder: see CONTRIBUTING.md and `pnpm new:service <id>`.',
    '',
  );
  const markdown = lines.join('\n');
  const config = (await resolveConfig(OUTPUT)) ?? {};
  return format(markdown, { ...config, filepath: OUTPUT });
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { check: { type: 'boolean' } }, strict: true });
  const { registry } = await loadServices();
  const fresh = await servicesMarkdown(registry.BUILT_IN_SITES);
  if (values.check !== true) {
    await writeFile(OUTPUT, fresh);
    process.stdout.write(`Wrote ${OUTPUT}\n`);
    return;
  }
  let committed: string | null = null;
  try {
    committed = await readFile(OUTPUT, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  if (committed !== fresh) {
    process.stderr.write(`Out of date: ${OUTPUT}. Run pnpm docs:services and commit the result.\n`);
    process.exitCode = 1;
    return;
  }
  process.stdout.write('docs/services.md is up to date with the registry.\n');
}

if (import.meta.main) await main();
