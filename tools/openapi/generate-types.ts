// The text of `packages/api/src/generated/schema.d.ts`: the MPL notice, a note saying how
// it is made, and what openapi-typescript prints for the subset.

import openapiTS, { astToString } from 'openapi-typescript';

import { NOTICE_LINES } from '../lint/mpl-header.js';
import type { OpenApiDoc } from './extract-subset.ts';

export const TYPES_HEADER = [
  `/* ${NOTICE_LINES[0]}`,
  ` * ${NOTICE_LINES[1]}`,
  ` * ${NOTICE_LINES[2]} */`,
  '',
  '// Generated by `pnpm openapi:sync` from tools/openapi/openapi.subset.json with',
  '// openapi-typescript. Do not edit: `pnpm openapi:check` fails when this file differs',
  '// from what the subset generates.',
  '',
  '',
].join('\n');

/**
 * The types of `subset`. Read-only (`immutable`): the extension sends and reads wire data,
 * it never edits it in place. A field with a default stays optional (`defaultNonNullable:
 * false`): a request may leave it out, and the server fills it in, so a body that omits it is
 * still the wire's. `subset` is not changed.
 */
export async function generateTypes(subset: OpenApiDoc): Promise<string> {
  const source = structuredClone(subset) as unknown as Parameters<typeof openapiTS>[0];
  const ast = await openapiTS(source, { immutable: true, silent: true, defaultNonNullable: false });
  return `${TYPES_HEADER}${astToString(ast)}`;
}
