// The extension's catalogs, compiled: every `src/i18n/messages/<locale>.json` — ICU
// MessageFormat, English the source — becomes one module of plain functions under
// `src/i18n/generated/`, so the bundle carries no MessageFormat parser. Plus the `en-XA`
// pseudo-locale for development builds, and the `_locales/` strings the manifest names.
//
// Loaded on demand: a page bundles English and `import()`s its UI language's module, one
// chunk per locale. The worker cannot `import()`; it bundles English's words for core's keys as
// data (`generated/worker.ts`) and reads its UI language's from `i18n/<locale>.json`, which the
// build writes (`workerFiles`).
//
//   node tools/i18n/compile.ts --write        regenerate src/i18n/generated/
//   node tools/i18n/compile.ts --check        fail when it is out of date, a key is unused,
//                                             or a translation has a key English does not
//   node tools/i18n/compile.ts --print=en.ts  print one generated file

import { readFile, readdir, writeFile, mkdir, rm } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

import { EXTENSION_NAME, PRODUCT_NAME } from '../../apps/extension/src/brand.ts';
import type { DataCatalog, WordNode } from '../../apps/extension/src/i18n/data.ts';
import {
  I18nError,
  compileData,
  compileMessage,
  messageFunction,
  plainText,
  pseudoData,
  str,
} from './icu.ts';
import { PSEUDO_LOCALE, WEB_LOCALES, folderLocales } from './locales-map.ts';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const MESSAGES_DIR = join(ROOT, 'apps/extension/src/i18n/messages');
export const GENERATED_DIR = join(ROOT, 'apps/extension/src/i18n/generated');
const APP_SOURCES = join(ROOT, 'apps/extension/src');
const CORE_KEYS_FILE = join(ROOT, 'packages/core/src/domain/messages.ts');

export const SOURCE_LOCALE = 'en';

/** The manifest's strings, by `_locales` message name: plain text, no plurals. */
export const MANIFEST_KEYS = {
  extName: 'manifest.extName',
  extDescription: 'manifest.extDescription',
} as const;

/** Chrome Web Store limits on the two manifest strings. */
const MANIFEST_LIMITS: Readonly<Record<keyof typeof MANIFEST_KEYS, number>> = {
  extName: 75,
  extDescription: 132,
};

const MPL_NOTICE = `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */`;

export type Messages = Readonly<Record<string, string>>;

const KEY = /^[a-z][A-Za-z0-9_]*(?:\.[a-z][A-Za-z0-9_]*)*$/u;

/** A catalog's module source: one function per key, sorted, so output is stable. */
export function compileCatalog(locale: string, messages: Messages): string {
  const lines = Object.keys(messages)
    .sort()
    .map((key) => {
      if (!KEY.test(key)) throw new I18nError(`${locale} ${key}: not a message key`);
      return `    ${str(key)}: ${compileMessage(locale, key, messages[key] ?? '')},`;
    });
  return catalogModule(locale, `${locale}.json`, lines);
}

/** The pseudo-locale's messages, English transformed, as checked trees by key, sorted. */
function pseudoMessages(messages: Messages): ReadonlyMap<string, WordNode[]> {
  return new Map(
    Object.keys(messages)
      .sort()
      .map((key) => [key, pseudoData(SOURCE_LOCALE, PSEUDO_LOCALE, key, messages[key] ?? '')]),
  );
}

/** The pseudo-locale's module source. */
export function compilePseudo(messages: Messages): string {
  const lines = [...pseudoMessages(messages)].map(
    ([key, nodes]) => `    ${str(key)}: ${messageFunction(nodes)},`,
  );
  return catalogModule(PSEUDO_LOCALE, `${SOURCE_LOCALE}.json (pseudo-locale)`, lines);
}

function catalogModule(locale: string, from: string, lines: readonly string[]): string {
  return [
    MPL_NOTICE,
    '',
    `// Generated by tools/i18n/compile.ts from src/i18n/messages/${from}: do not edit.`,
    '// `pnpm i18n:compile` writes it; `pnpm i18n:check` fails while it is out of date.',
    '',
    "import type { Catalog } from '../runtime';",
    '',
    'export const catalog: Catalog = {',
    `  locale: ${str(locale)},`,
    '  messages: {',
    ...lines,
    '  },',
    '};',
    '',
  ].join('\n');
}

const identifier = (locale: string): string => locale.replace(/-/gu, '_');

/**
 * `generated/index.ts`, the pages' catalogs: English imported (every page carries it, the
 * fallback key by key), every other locale and the pseudo-locale behind an `import()` (one
 * chunk each, loaded when the UI language asks for it), and the key type English defines.
 */
export function compileIndex(locales: readonly string[], source: Messages): string {
  const keys = Object.keys(source).sort();
  const translations = locales.filter((locale) => locale !== SOURCE_LOCALE);
  return [
    MPL_NOTICE,
    '',
    '// Generated by tools/i18n/compile.ts: do not edit.',
    '',
    "import type { Catalog } from '../runtime';",
    `import { catalog as ${identifier(SOURCE_LOCALE)} } from './${SOURCE_LOCALE}';`,
    '',
    '/** Every key the source catalog defines: what `t()` takes. */',
    'export type AppMessageKey =',
    ...keys.map((key, i) => `  | ${str(key)}${i === keys.length - 1 ? ';' : ''}`),
    '',
    '/** The source catalog: in every page, the fallback key by key. */',
    `export const SOURCE_CATALOG: Catalog = ${identifier(SOURCE_LOCALE)};`,
    '',
    '/** Every other catalog by locale, loaded when a page needs it: one chunk each. */',
    'export const TRANSLATIONS: Readonly<Record<string, () => Promise<Catalog>>> = {',
    ...translations.map(
      (locale) => `  ${str(locale)}: async () => (await import('./${locale}')).catalog,`,
    ),
    '};',
    '',
    '/** The development-only pseudo-locale. */',
    `export const PSEUDO_LOCALE = ${str(PSEUDO_LOCALE)};`,
    '',
    '/**',
    " * Its catalog's loader, in a development build alone: `null` elsewhere. The condition reads",
    ' * the mode the build inlines, here: the bundler leaves an `import()` and its chunk out only',
    ' * under a condition it can fold in the module that holds it.',
    ' */',
    'export const loadPseudoCatalog: (() => Promise<Catalog>) | null =',
    "  import.meta.env.MT_BUILD_MODE === 'development'",
    `    ? async () => (await import('./${PSEUDO_LOCALE}')).catalog`,
    '    : null;',
    '',
  ].join('\n');
}

/** A catalog's words for `keys` (core's), as data: what the worker renders. */
function workerCatalog(locale: string, messages: Messages, keys: ReadonlySet<string>): DataCatalog {
  const out: Record<string, WordNode[]> = {};
  for (const key of Object.keys(messages).sort()) {
    if (keys.has(key)) out[key] = compileData(locale, key, messages[key] ?? '');
  }
  return { locale, messages: out };
}

function pseudoWorkerCatalog(source: Messages, keys: ReadonlySet<string>): DataCatalog {
  const out: Record<string, WordNode[]> = {};
  for (const [key, nodes] of pseudoMessages(source)) if (keys.has(key)) out[key] = nodes;
  return { locale: PSEUDO_LOCALE, messages: out };
}

/**
 * `generated/worker.ts`, the worker's catalogs: English's words for core's keys as data (in the
 * worker's bundle, the fallback key by key) and the locales whose words it reads from the
 * package instead.
 */
export function compileWorker(
  catalogs: ReadonlyMap<string, Messages>,
  keys: ReadonlySet<string>,
): string {
  const source = catalogs.get(SOURCE_LOCALE);
  if (source === undefined) throw new I18nError(`no ${SOURCE_LOCALE} catalog`);
  const translations = [...catalogs.keys()].filter((locale) => locale !== SOURCE_LOCALE);
  const words = workerCatalog(SOURCE_LOCALE, source, keys);
  return [
    MPL_NOTICE,
    '',
    '// Generated by tools/i18n/compile.ts from src/i18n/messages/: do not edit.',
    '// `pnpm i18n:compile` writes it; `pnpm i18n:check` fails while it is out of date.',
    '',
    "import type { DataCatalog } from '../data';",
    '',
    "/** English's words for core's keys: in the worker's bundle, the fallback key by key. */",
    'export const SOURCE_WORDS: DataCatalog = {',
    `  locale: ${str(SOURCE_LOCALE)},`,
    '  messages: {',
    ...Object.entries(words.messages).map(([key, nodes]) => `    ${str(key)}: ${str(nodes)},`),
    '  },',
    '};',
    '',
    "/** The other locales: their words are `i18n/<locale>.json` in the package (the build's). */",
    `export const WORKER_TRANSLATIONS: readonly string[] = ${JSON.stringify(translations)};`,
    '',
    '/** The development-only pseudo-locale: a development build alone carries its file. */',
    `export const PSEUDO_LOCALE = ${str(PSEUDO_LOCALE)};`,
    '',
  ].join('\n');
}

/**
 * The worker's catalogs the build writes into the package, path → contents: one
 * `i18n/<locale>.json` per locale but English (bundled), and the pseudo-locale's when asked —
 * in development builds only.
 */
export function workerFiles(
  catalogs: ReadonlyMap<string, Messages>,
  keys: ReadonlySet<string>,
  options: { readonly pseudo: boolean },
): ReadonlyMap<string, string> {
  const source = catalogs.get(SOURCE_LOCALE);
  if (source === undefined) throw new I18nError(`no ${SOURCE_LOCALE} catalog`);
  const out = new Map<string, string>();
  for (const [locale, messages] of catalogs) {
    if (locale === SOURCE_LOCALE) continue;
    out.set(`i18n/${locale}.json`, JSON.stringify(workerCatalog(locale, messages, keys)));
  }
  if (options.pseudo) {
    out.set(`i18n/${PSEUDO_LOCALE}.json`, JSON.stringify(pseudoWorkerCatalog(source, keys)));
  }
  return out;
}

/** Every catalog on disk, by locale, English first. */
export async function readCatalogs(): Promise<ReadonlyMap<string, Messages>> {
  const files = (await readdir(MESSAGES_DIR)).filter((f) => f.endsWith('.json')).sort();
  const out = new Map<string, Messages>();
  for (const file of files) {
    const locale = file.slice(0, -'.json'.length);
    if (!(WEB_LOCALES as readonly string[]).includes(locale)) {
      throw new I18nError(`messages/${file}: ${locale} is not one of the web app's locales`);
    }
    const parsed: unknown = JSON.parse(await readFile(join(MESSAGES_DIR, file), 'utf8'));
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
      throw new I18nError(`messages/${file}: not an object of messages`);
    }
    for (const [key, value] of Object.entries(parsed)) {
      if (typeof value !== 'string') throw new I18nError(`${locale} ${key}: not a string`);
    }
    out.set(locale, parsed as Messages);
  }
  if (!out.has(SOURCE_LOCALE)) throw new I18nError(`messages/${SOURCE_LOCALE}.json is missing`);
  return new Map(
    [...out].sort(([a], [b]) => Number(b === SOURCE_LOCALE) - Number(a === SOURCE_LOCALE)),
  );
}

/**
 * The generated directory's files, by name: what `--write` writes and `--check` compares.
 * `coreKeys` are the worker's (`readCoreKeys`).
 */
export function generate(
  catalogs: ReadonlyMap<string, Messages>,
  coreKeys: ReadonlySet<string>,
): ReadonlyMap<string, string> {
  const source = catalogs.get(SOURCE_LOCALE);
  if (source === undefined) throw new I18nError(`no ${SOURCE_LOCALE} catalog`);
  const files = new Map<string, string>();
  for (const [locale, messages] of catalogs) {
    if (locale !== SOURCE_LOCALE) {
      const extra = Object.keys(messages).filter((key) => !Object.hasOwn(source, key));
      if (extra.length > 0) {
        throw new I18nError(`${locale}: keys English does not have: ${extra.join(', ')}`);
      }
    }
    files.set(`${locale}.ts`, compileCatalog(locale, messages));
  }
  files.set(`${PSEUDO_LOCALE}.ts`, compilePseudo(source));
  files.set('index.ts', compileIndex([...catalogs.keys()], source));
  files.set('worker.ts', compileWorker(catalogs, coreKeys));
  return files;
}

/** Renders a plain message (literals and arguments only) with the brand's names. */
function renderPlain(locale: string, key: string, message: string): string {
  return plainText(locale, key, message, { product: PRODUCT_NAME, extension: EXTENSION_NAME });
}

/**
 * The `_locales/<folder>/messages.json` files (path → contents) the manifest's `__MSG_…__`
 * names read: one folder per locale with a catalog (`folderLocales`), each string falling back
 * to English where a translation lacks it.
 */
export function localeFiles(catalogs: ReadonlyMap<string, Messages>): ReadonlyMap<string, string> {
  const source = catalogs.get(SOURCE_LOCALE);
  if (source === undefined) throw new I18nError(`no ${SOURCE_LOCALE} catalog`);
  const out = new Map<string, string>();
  for (const [folder, locale] of folderLocales([...catalogs.keys()])) {
    const messages = catalogs.get(locale) ?? source;
    const entries = Object.entries(MANIFEST_KEYS).map(([name, key]) => {
      const message = messages[key] ?? source[key];
      if (message === undefined) throw new I18nError(`${SOURCE_LOCALE} ${key}: missing`);
      const text = renderPlain(locale, key, message);
      const limit = MANIFEST_LIMITS[name as keyof typeof MANIFEST_KEYS];
      if (Array.from(text).length > limit) {
        throw new I18nError(`${locale} ${key}: longer than ${String(limit)} characters`);
      }
      return [name, { message: text }] as const;
    });
    out.set(
      `_locales/${folder}/messages.json`,
      `${JSON.stringify(Object.fromEntries(entries), null, 2)}\n`,
    );
  }
  return out;
}

async function sourceFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (path !== GENERATED_DIR) out.push(...(await sourceFiles(path)));
    } else if (/\.(?:ts|tsx)$/u.test(entry.name)) {
      out.push(path);
    }
  }
  return out;
}

/**
 * The keys core's `MessageKey` names (`packages/core/src/domain/messages.ts`): what the worker
 * renders (the icon's tooltip), so what its catalogs carry.
 */
export async function readCoreKeys(): Promise<ReadonlySet<string>> {
  const text = await readFile(CORE_KEYS_FILE, 'utf8');
  return new Set([...text.matchAll(/'([a-z][a-z0-9_.]*)'/gu)].map((m) => m[1] ?? ''));
}

/**
 * Problems `--check` reports: a generated file out of date or stale, a core key without English
 * text, an English key nothing refers to (core's union, the app's sources as a quoted literal,
 * or the manifest's strings).
 */
export async function check(): Promise<readonly string[]> {
  const problems: string[] = [];
  const catalogs = await readCatalogs();
  const core = await readCoreKeys();
  const expected = generate(catalogs, core);
  const onDisk = new Set(
    (await readdir(GENERATED_DIR).catch(() => [] as string[])).filter((f) => f.endsWith('.ts')),
  );
  for (const [name, contents] of expected) {
    const actual = onDisk.has(name) ? await readFile(join(GENERATED_DIR, name), 'utf8') : null;
    if (actual !== contents) {
      problems.push(`generated/${name} is out of date: run pnpm i18n:compile`);
    }
  }
  for (const name of onDisk) {
    if (!expected.has(name)) {
      problems.push(`generated/${name} has no catalog: run pnpm i18n:compile`);
    }
  }
  localeFiles(catalogs);
  workerFiles(catalogs, core, { pseudo: true });

  const source = catalogs.get(SOURCE_LOCALE) ?? {};
  for (const key of core) {
    if (!Object.hasOwn(source, key)) problems.push(`core key ${key} has no English text`);
  }
  const texts = await Promise.all(
    (await sourceFiles(APP_SOURCES)).map((file) => readFile(file, 'utf8')),
  );
  const manifest = new Set<string>(Object.values(MANIFEST_KEYS));
  for (const key of Object.keys(source)) {
    if (core.has(key) || manifest.has(key)) continue;
    const quoted = [`'${key}'`, `"${key}"`, `\`${key}\``];
    if (!texts.some((text) => quoted.some((q) => text.includes(q)))) {
      problems.push(`${key} is not used: remove it from messages/${SOURCE_LOCALE}.json`);
    }
  }
  return problems;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      write: { type: 'boolean', default: false },
      check: { type: 'boolean', default: false },
      print: { type: 'string' },
    },
    strict: true,
  });
  if (values.check) {
    const problems = await check();
    for (const problem of problems) process.stderr.write(`i18n: ${problem}\n`);
    if (problems.length > 0) process.exitCode = 1;
    else process.stdout.write('i18n: catalogs are compiled and every key is used\n');
    return;
  }
  const files = generate(await readCatalogs(), await readCoreKeys());
  if (values.print !== undefined) {
    const contents = files.get(values.print);
    if (contents === undefined) throw new I18nError(`no generated file ${values.print}`);
    process.stdout.write(contents);
    return;
  }
  if (!values.write) {
    process.stderr.write('usage: compile.ts --write | --check | --print=<file>\n');
    process.exitCode = 2;
    return;
  }
  await rm(GENERATED_DIR, { recursive: true, force: true });
  await mkdir(GENERATED_DIR, { recursive: true });
  for (const [name, contents] of files) await writeFile(join(GENERATED_DIR, name), contents);
  process.stdout.write(
    `i18n: wrote ${String(files.size)} files to ${relative(ROOT, GENERATED_DIR)}\n`,
  );
}

if (import.meta.main) await main();
